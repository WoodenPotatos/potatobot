"""The PostgreSQL type of every column, decided once, for the 2.20 move.

Phase 2's baseline schema and Phase 3's copy from SQLite both read this map
(todo.md, "2.20.0: PostgreSQL"; docs/subsystems/database.md). SQLite stores
almost everything as INTEGER or TEXT, so what a TEXT column *means* -- an
instant, a JSON document, or text -- is written down here rather than guessed
from its name at copy time, where a wrong guess silently corrupts a row.

`tests/test_database_transactions.py` holds it to the schema
`initialize_database()` creates, in both directions: a column added without an
entry, or an entry for a column that is gone, fails the suite.

Decided, and why:

- **INSTANT is `timestamptz`.** Every time column holds an ISO instant written
  by `utc_now().isoformat()` (measured against the development database and
  every writer, 2026-10-31); none holds a bare calendar date, so there is no
  `date` kind. A legacy value with no offset is host-local, and the copy
  converts it the way `clock.parse_stored` reads it.
- **JSON is `text` in 2.20.** `jsonb` would hand back parsed objects, break
  every `json.loads` of a column, and normalise the text that LFG's
  compare-and-set matches exactly. Converting later is one
  `ALTER ... USING col::jsonb`, when a query needs JSON operators.
- **FLAG is `smallint`** with its existing `CHECK (x IN (0, 1))`, so Python
  keeps reading 0 and 1. A boolean that has no such CHECK stays BIGINT.
- **IDENTITY is an `AUTOINCREMENT` key**: `bigint GENERATED BY DEFAULT AS
  IDENTITY`, so the copy can insert the existing ids and then move each
  sequence past them. Like AUTOINCREMENT, it never reuses a pruned id.
- **BIGINT is every other INTEGER.** SQLite's INTEGER is 64-bit, PostgreSQL's
  is 32-bit; a snowflake or a balance does not fit the latter.
"""

