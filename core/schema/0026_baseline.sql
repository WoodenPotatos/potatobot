-- PostgreSQL baseline: the schema SQLite reached at version 26.
--
-- Generated once from SQLite's own DDL with every column typed by
-- core/schema_types.py, then committed and reviewed; it is the source of truth
-- from here, and later migrations number on from it (0027_*.sql). The
-- translation changed column types and nothing else: every CHECK, default,
-- key, foreign key and index is SQLite's, which needed no other change.
-- Tables are ordered so a foreign key's target exists first.
-- todo.md, "2.20.0: PostgreSQL"; docs/subsystems/database.md.

CREATE TABLE schema_migrations (
    version integer PRIMARY KEY,
    applied_at timestamptz NOT NULL
);

